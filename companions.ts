// ─── Helper: getCompanionPhrase ───────────────────────────────────────────────

/**
 * Returns a phrase for the given companion.
 *
 * @param companionId  - which companion to use
 * @param moment       - optional context (not yet used for filtering, ready for extension)
 * @param recentlyUsed - array of phrases used recently; avoided when possible
 */
export function getCompanionPhrase(
  companionId: CompanionId,
  moment?: CompanionMoment,
  recentlyUsed: string[] = []
): string {
  const companion = companions.find((c) => c.id === companionId);
  if (!companion || companion.phrases.length === 0) return "";

  const pool = companion.phrases;

  // Filter out recently used phrases; fall back to full pool if all are "used"
  const available =
    pool.filter((p) => !recentlyUsed.includes(p)).length > 0
      ? pool.filter((p) => !recentlyUsed.includes(p))
      : pool;

  return available[Math.floor(Math.random() * available.length)];
}

// ─── Lookup helper ────────────────────────────────────────────────────────────

export function getCompanion(id: CompanionId): Companion | undefined {
  return companions.find((c) => c.id === id);
}
